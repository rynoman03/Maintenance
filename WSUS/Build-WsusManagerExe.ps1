<#
.SYNOPSIS
    Builds the portable, single-file WsusManager.exe.

.DESCRIPTION
    1. Merges WsusManager.ps1 (launcher), WsusManager.psm1 (module) and the
       default WsusClientBaseline.json into one self-contained script
       (dist\WsusManager.combined.ps1).
    2. Compiles that script into dist\WsusManager.exe with PS2EXE
       (https://github.com/MScholtes/PS2EXE). The exe runs on Windows
       PowerShell 5.1, which is built into every supported Windows version,
       so there is nothing to install on the machine that runs it.
    3. Copies WsusClientBaseline.json next to the exe so the baseline can be
       edited without rebuilding (the exe falls back to its embedded copy if
       the file is not there).

    Run on Windows. PS2EXE is installed for the current user from the
    PowerShell Gallery if it is missing (use -SkipCompile to only produce the
    combined script, e.g. on a machine without Gallery access).

.EXAMPLE
    .\Build-WsusManagerExe.ps1

.EXAMPLE
    .\Build-WsusManagerExe.ps1 -OutputDirectory C:\Tools\WsusManager -IconFile .\wsus.ico
#>

[CmdletBinding()]
param(
    [string]$OutputDirectory = (Join-Path $PSScriptRoot 'dist'),

    [string]$IconFile,

    [switch]$SkipCompile
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version 2.0

$launcherPath = Join-Path $PSScriptRoot 'WsusManager.ps1'
$modulePath = Join-Path $PSScriptRoot 'WsusManager.psm1'
$manifestPath = Join-Path $PSScriptRoot 'WsusManager.psd1'
$baselinePath = Join-Path $PSScriptRoot 'WsusClientBaseline.json'

$launcher = Get-Content -LiteralPath $launcherPath -Raw
$module = Get-Content -LiteralPath $modulePath -Raw
$baseline = Get-Content -LiteralPath $baselinePath -Raw

# Fail early on a broken baseline rather than shipping it inside the exe.
$null = $baseline | ConvertFrom-Json

if ($baseline -match "(?m)^'@") {
    throw 'WsusClientBaseline.json cannot contain a line starting with '' @ (it would end the embedding here-string).'
}

# Module body without its Export-ModuleMember block (everything is in one script now).
$exportIndex = $module.IndexOf('Export-ModuleMember')
if ($exportIndex -lt 0) {
    throw 'Export-ModuleMember block not found in WsusManager.psm1.'
}
$moduleBody = $module.Substring(0, $exportIndex).TrimEnd()

# In the exe the module and the launcher share one script scope, so a module
# $script: variable with the same name as a launcher parameter would silently
# overwrite that parameter.
$launcherAst = [System.Management.Automation.Language.Parser]::ParseInput($launcher, [ref]$null, [ref]$null)
$paramNames = @($launcherAst.ParamBlock.Parameters | ForEach-Object { $_.Name.VariablePath.UserPath })
$moduleVars = @([regex]::Matches($moduleBody, '\$script:(\w+)') | ForEach-Object { $_.Groups[1].Value } | Select-Object -Unique)
$clash = @($paramNames | Where-Object { $moduleVars -contains $_ })
if ($clash) {
    throw "Module script variable(s) collide with launcher parameter(s): $($clash -join ', ')."
}

$startMarker = '# <WSUSMANAGER-MODULE>'
$endMarker = '# </WSUSMANAGER-MODULE>'
$start = $launcher.IndexOf($startMarker)
$end = $launcher.IndexOf($endMarker)
if ($start -lt 0 -or $end -lt $start) {
    throw "Module markers not found in WsusManager.ps1."
}
$end += $endMarker.Length

$embedded = @(
    '#region Embedded WsusManager module (generated by Build-WsusManagerExe.ps1 - do not edit here)'
    "`$script:EmbeddedBaselineJson = @'"
    $baseline.TrimEnd()
    "'@"
    ''
    $moduleBody
    '#endregion'
) -join "`r`n"

$combined = $launcher.Substring(0, $start) + $embedded + $launcher.Substring($end)
$combined = $combined -replace "`r?`n", "`r`n"

# Check the merged script parses before compiling it.
$tokens = $null
$errors = $null
[void][System.Management.Automation.Language.Parser]::ParseInput($combined, [ref]$tokens, [ref]$errors)
if ($errors) {
    $errors | ForEach-Object { Write-Host "  line $($_.Extent.StartLineNumber): $($_.Message)" -ForegroundColor Red }
    throw 'The combined script does not parse.'
}

if (-not (Test-Path -LiteralPath $OutputDirectory)) {
    New-Item -ItemType Directory -Path $OutputDirectory -Force | Out-Null
}
$combinedPath = Join-Path $OutputDirectory 'WsusManager.combined.ps1'
[System.IO.File]::WriteAllText($combinedPath, $combined, (New-Object System.Text.UTF8Encoding($false)))
Copy-Item -LiteralPath $baselinePath -Destination (Join-Path $OutputDirectory 'WsusClientBaseline.json') -Force
Write-Host "Combined script: $combinedPath"

if ($SkipCompile) {
    return
}

if ($PSVersionTable.PSEdition -eq 'Core' -and -not $IsWindows) {
    throw 'Compiling the exe requires Windows. Use -SkipCompile to only build the combined script.'
}

if (-not (Get-Module -ListAvailable -Name ps2exe)) {
    Write-Host 'Installing PS2EXE for the current user from the PowerShell Gallery...'
    Install-Module -Name ps2exe -Scope CurrentUser -Force
}
Import-Module ps2exe

$version = (Import-PowerShellDataFile -LiteralPath $manifestPath).ModuleVersion
$exePath = Join-Path $OutputDirectory 'WsusManager.exe'

$ps2exeParams = @{
    inputFile   = $combinedPath
    outputFile  = $exePath
    title       = 'WSUS Manager'
    description = 'WSUS update-group reporting and Windows Update client control'
    product     = 'WSUS Manager'
    company     = 'Maintenance'
    version     = $version
}
if ($IconFile) {
    $ps2exeParams['iconFile'] = (Resolve-Path -LiteralPath $IconFile).Path
}

Invoke-ps2exe @ps2exeParams

if (-not (Test-Path -LiteralPath $exePath)) {
    throw 'PS2EXE did not produce WsusManager.exe.'
}
Write-Host "Built $exePath (version $version)" -ForegroundColor Green
